//  玩家看到：主線的夢（第 1～10 夜）每走進新的一區，就默默記下「這一區的入口」；在區裡倒下時，
//    死亡畫面多一顆「回到這一區的入口」鈕，前面打過的區、這一區還沒打的怪和地上的東西都留著。
//    （首領巢穴照舊回到首領之門前；深層夢境照舊：沒開傳送門就失去這張地圖）
//  資料：G.world.ckpt = { x, y, k }（跟著地圖，不另外存檔）
//  接點：Hook 'update'；game.js 的 playerDie 看 w.ckpt 決定 keep = 'zone'；deathhelp.js 的按鈕
// =============================================================
Hook.on('update', () => {
  const w = G.world, pl = G.pl; if (!w || !pl || w.kind !== 'map' || G.dead) return;
  const k = (w.stage && w.stage.i) || 1;
  if (!w.ckpt || k > w.ckpt.k) w.ckpt = { x: pl.x, y: pl.y, k };
});
